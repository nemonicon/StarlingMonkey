// Independent optional Querystring packaging. No shared build/generator edits.
// Run: node builtins/node-compat/generate-querystring-factories.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateManifest } from './validate-manifest.mjs';
const directory = dirname(fileURLToPath(import.meta.url));
const names = ['querystring.mjs', 'export-manifest.querystring.node-v22.14.0.json'];
const sources = Object.fromEntries(await Promise.all(names.map(async name => [name, await readFile(join(directory, name), 'utf8')])));
const manifest = JSON.parse(sources[names[1]]);
validateManifest(manifest, JSON.parse(await readFile(join(directory, 'manifest.schema.json'), 'utf8')));
if (manifest.profileVersion !== 'sm-node-22.14.0-m0.6') throw new Error('Unexpected Querystring profile version');
const bindings = new Map();
let body = sources['querystring.mjs'];
const imported = "import { Buffer as BufferCtor } from 'node:buffer';\n";
if (!body.includes(imported)) throw new Error('Missing exact private Buffer injection boundary');
body = body.replace(imported, '');
body = body.replace(/^export\s*\{([^}]+)\};\n?/gm, (_, clause) => {
  for (const entry of clause.split(',')) {
    const match = entry.trim().match(/^([A-Za-z_$][A-Za-z0-9_$]*)(?:\s+as\s+([A-Za-z_$][A-Za-z0-9_$]*))?$/);
    if (!match) throw new Error('Unsupported Querystring export clause');
    const name = match[2] ?? match[1];
    if (bindings.has(name)) throw new Error('Duplicate Querystring binding');
    bindings.set(name, match[1]);
  }
  return '';
});
body = body.replace(/^export default ([A-Za-z_$][A-Za-z0-9_$]*);\n?/m, (_, name) => {
  if (bindings.has('default')) throw new Error('Duplicate Querystring default binding');
  bindings.set('default', name); return '';
});
if (/^\s*(?:import|export)\b/m.test(body)) throw new Error('Unsupported Querystring module syntax');
const exports = manifest.modules['node:querystring'].exports;
if ([...bindings.keys()].sort().join(',') !== [...exports].sort().join(',')) throw new Error('Querystring source/manifest export mismatch');
// evaluate_factory passes the already-rooted existing Buffer constructor. All
// bindings remain private to the returned callable; globalThis.Buffer is unused.
const factory = `((BufferCtor) => {\nconst __smNodeQueryFreeze = Object.freeze;\n${body}\nreturn __smNodeQueryFreeze({ ${exports.map(name => `${name}: ${bindings.get(name)}`).join(', ')} });\n})`;
if (factory.includes(')SM_NODE_PROFILE"')) throw new Error('Querystring raw-string delimiter collision');
const digest = createHash('sha256');
for (const name of names) digest.update(name+'\0'+sources[name]+'\0');
const output = '// Generated by generate-querystring-factories.mjs; do not edit.\n'+
  `// Canonical-source SHA-256: ${digest.digest('hex')}\n`+
  `static constexpr const char kQuerystringFactorySource[] = R"SM_NODE_PROFILE(${factory})SM_NODE_PROFILE";\n`;
const path = join(directory, 'querystring-factories.generated.h');
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== output) throw new Error('Stale querystring-factories.generated.h');
  console.log('PASS optional Querystring factory/schema/exports match canonical sources');
} else await writeFile(path, output);
