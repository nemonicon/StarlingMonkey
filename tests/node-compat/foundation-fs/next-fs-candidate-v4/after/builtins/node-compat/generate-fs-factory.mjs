// Explicit optional packaging in this file's genuine directory context.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import fs from 'node:fs';
import fsPromises from 'node:fs/promises';
import {validateManifest} from './validate-manifest.mjs';
if(process.version!=='v22.14.0')throw new Error('Expected pinned Node22.14.0');
const here=dirname(fileURLToPath(import.meta.url));
const names=['fs-facade.mjs','fs-inventory.json','export-manifest.fs.node-v22.14.0.json'];
const texts=await Promise.all(names.map(n=>readFile(join(here,n),'utf8')));
const inventory=JSON.parse(texts[1]),manifest=JSON.parse(texts[2]);
validateManifest(manifest,JSON.parse(await readFile(join(here,'manifest.schema.json'),'utf8')));
for(const [key,actual,id] of [['fsExports',fs,'node:fs'],['promiseExports',fsPromises,'node:fs/promises']]){
 if(JSON.stringify(Object.keys(actual).sort())!==JSON.stringify(inventory[key]))throw new Error('Node22 inventory drift');
 if(JSON.stringify([...inventory[key],'default'].sort())!==JSON.stringify(manifest.modules[id].exports))throw new Error('Manifest export drift');
}
if(manifest.profileVersion!=='sm-node-22.14.0-m0.20')throw new Error('Unexpected FS profile');
let body=texts[0].replace(/^export function createFsModules/m,'function createFsModules');
if(/^\s*(?:import|export)\b/m.test(body))throw new Error('Unexpected factory syntax');
const factory=`((dependencies)=>{\n${body}\nreturn createFsModules({kernel:dependencies.kernel,Buffer:dependencies.Buffer,Readable:dependencies.Readable,nextTick:dependencies.nextTick,inventory:${JSON.stringify(inventory)}});\n})`;
if(factory.includes(')SM_NODE_PROFILE"'))throw new Error('Raw delimiter collision');
const hash=createHash('sha256');for(let i=0;i<names.length;i++)hash.update(names[i]+'\0'+texts[i]+'\0');
const output=`// Generated by generate-fs-factory.mjs; do not edit.\n// Canonical-source SHA-256: ${hash.digest('hex')}\nstatic constexpr const char kFsFactorySource[] = R"SM_NODE_PROFILE(${factory})SM_NODE_PROFILE";\n`;
const path=join(here,'fs-factories.generated.h');
if(process.argv.includes('--check')){if(await readFile(path,'utf8')!==output)throw new Error('Stale FS header');}
else await writeFile(path,output);
console.log('PASS FS factory/manifest matches exact Node22 namespace');
