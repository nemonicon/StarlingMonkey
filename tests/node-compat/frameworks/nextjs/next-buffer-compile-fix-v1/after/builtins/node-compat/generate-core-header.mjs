// Dependency-free packaging for this small, deliberately restricted source set.
// Run `node builtins/node-compat/generate-factories.mjs [--check]`.
// Normal CMake builds use the checked-in output; they never execute Node/npm.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateManifest } from './validate-manifest.mjs';

const directory = dirname(fileURLToPath(import.meta.url));
const names = ['unsupported.mjs', 'buffer-facade.mjs', 'child-process.mjs', 'export-manifest.node-v22.14.0.json'];
const sources = Object.fromEntries(await Promise.all(names.map(async name => [name, await readFile(join(directory, name), 'utf8')])));
const manifest = JSON.parse(sources['export-manifest.node-v22.14.0.json']);
validateManifest(manifest, JSON.parse(await readFile(join(directory, 'manifest.schema.json'), 'utf8')));
const digest = createHash('sha256');
for (const name of names) digest.update(name + '\0' + sources[name] + '\0');

function scriptBody(name) {
  let source = sources[name];
  // These are exact accepted source forms, not a general JavaScript bundler.
  source = source.replace(/^import \{ (?:unavailable, unsupported|unsupported) \} from '\.\/unsupported\.mjs';\n/m, '');
  source = source.replace(/^export (const|function) /gm, '$1 ');
  source = source.replace(/^export default Object\.freeze\(/m, 'const defaultExport = Object.freeze(');
  if (/^\s*(?:import|export)\b/m.test(source)) throw new Error(`unsupported module syntax in ${name}`);
  return source;
}
const helper = scriptBody('unsupported.mjs');
const buffer = `(() => {\n${helper}\n${scriptBody('buffer-facade.mjs')}\nreturn createBufferModule;\n})()`;
const childNames = manifest.modules['node:child_process'].exports.filter(name => name !== 'default');
for (const name of childNames) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name)) throw new Error(`unsafe binding ${name}`);
}
const child = `(() => {\n${helper}\n${scriptBody('child-process.mjs')}\nreturn () => Object.freeze({ ${childNames.join(', ')}, default: defaultExport });\n})()`;
function definition(name, source) {
  if (source.includes(')SM_NODE_PROFILE"')) throw new Error('raw-string delimiter collision');
  return `static constexpr const char ${name}[] = R"SM_NODE_PROFILE(${source})SM_NODE_PROFILE";\n`;
}
const output = '// Generated by generate-factories.mjs; do not edit.\n' +
  `// Canonical-source SHA-256: ${digest.digest('hex')}\n` +
  definition('kBufferFactorySource', buffer) + definition('kChildProcessFactorySource', child);
const outputPath = join(directory, 'factories.generated.h');
if (process.argv.includes('--check')) {
  if (await readFile(outputPath, 'utf8') !== output) throw new Error('stale factories.generated.h; regenerate it');
  console.log('PASS checked-in Node profile factories match canonical sources');
} else {
  await writeFile(outputPath, output);
}

