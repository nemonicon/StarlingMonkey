// Maintainer-only bundling. Normal CMake builds use checked-in generated text.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadToolchain } from '../toolchain.mjs';
const here = dirname(fileURLToPath(import.meta.url));
const repository = resolve(here, '../../..');
const directory = join(repository, 'builtins/node-compat');
const vendor = join(directory, 'path-vendor');
const manifestBytes = await readFile(join(vendor, 'source-manifest.json'));
const manifest = JSON.parse(manifestBytes);
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
for (const entry of [...manifest.files, ...manifest.profileFiles]) {
  assert.equal(hash(await readFile(join(repository, entry.path))), entry.adaptedSha256 ?? entry.sha256, entry.path);
}
const { rolldown } = await loadToolchain();
const build = await rolldown({ input: join(vendor, 'entry.mjs'), platform: 'neutral', treeshake: true });
let code;
try {
  const { output } = await build.generate({ format: 'esm', codeSplitting: false });
  assert.equal(output.length, 1); assert.deepEqual(output[0].imports, []);
  code = output[0].code;
} finally { await build.close(); }
const license = await readFile(join(vendor, 'LICENSES.txt'), 'utf8');
assert(!license.includes('*/'));
const result = `// Generated by foundation-path/generate-matcher.mjs; do not edit.\n` +
  `// Vendor manifest SHA-256: ${hash(manifestBytes)}\n/*\n${license}\n*/\n${code}`;
const destination = join(directory, 'path-matcher.mjs');
if (process.argv.includes('--check')) {
  assert.equal(await readFile(destination, 'utf8'), result, 'stale generated path-matcher.mjs');
  console.log('PASS pinned, patched Path matcher bundle is current');
} else { await writeFile(destination, result); console.log(destination); }
