// Independent optional Assert packaging. Shared generator/CMake stay untouched.
// Run: node builtins/node-compat/generate-assert-factories.mjs [--check]
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateManifest } from './validate-manifest.mjs';
const directory = dirname(fileURLToPath(import.meta.url));
const names = ['assert.mjs', 'assert-strict.mjs', 'export-manifest.assert.node-v22.14.0.json'];
const sources = Object.fromEntries(await Promise.all(names.map(async name => [name, await readFile(join(directory, name), 'utf8')])));
const manifest = JSON.parse(sources[names[2]]);
validateManifest(manifest, JSON.parse(await readFile(join(directory, 'manifest.schema.json'), 'utf8')));
if (manifest.profileVersion !== 'sm-node-22.14.0-m0.5') throw new Error('Unexpected Assert profile version');
const identifier = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const bindings = new Map();
function add(exported, local) {
  if (!identifier.test(exported) || !identifier.test(local) || bindings.has(exported)) throw new Error('Invalid/duplicate Assert binding '+exported);
  bindings.set(exported, local);
}
let body = sources['assert.mjs'].replace(/^export (class|function|const) ([A-Za-z_$][A-Za-z0-9_$]*)/gm,
  (_, kind, name) => { add(name, name); return kind+' '+name; });
body = body.replace(/^export \{ ([^}]+) \};\n?/gm, (_, clause) => {
  for (const entry of clause.split(',')) {
    const match = entry.trim().match(/^([A-Za-z_$][A-Za-z0-9_$]*)(?:\s+as\s+([A-Za-z_$][A-Za-z0-9_$]*))?$/);
    if (!match) throw new Error('Unsupported Assert export clause');
    add(match[2] ?? match[1], match[1]);
  }
  return '';
});
body = body.replace(/^export default ([A-Za-z_$][A-Za-z0-9_$]*);\n?/m, (_, local) => { add('default', local); return ''; });
if (/^\s*(?:import|export)\b/m.test(body)) throw new Error('Unsupported Assert module syntax');
const rootNames = manifest.modules['node:assert'].exports;
if ([...bindings.keys()].sort().join(',') !== [...rootNames].sort().join(',')) throw new Error('Assert source/manifest export mismatch');
const strictSource = sources['assert-strict.mjs'].replace(/^\/\/.*\n/gm, '').trim();
const strictMatch = strictSource.match(/^export\s*\{([\s\S]+)\}\s*from '\.\/assert\.mjs';$/);
if (!strictMatch) throw new Error('Unsupported Assert strict module syntax');
const strictBindings = new Map();
for (const entry of strictMatch[1].split(',')) {
  const match = entry.trim().match(/^([A-Za-z_$][A-Za-z0-9_$]*)(?:\s+as\s+([A-Za-z_$][A-Za-z0-9_$]*))?$/);
  if (!match || !bindings.has(match[1])) throw new Error('Invalid Assert strict reexport');
  const name = match[2] ?? match[1];
  if (strictBindings.has(name)) throw new Error('Duplicate Assert strict binding');
  strictBindings.set(name, bindings.get(match[1]));
}
const strictNames = manifest.modules['node:assert/strict'].exports;
if ([...strictBindings.keys()].sort().join(',') !== [...strictNames].sort().join(',')) throw new Error('Assert strict source/manifest export mismatch');
const record = (names, map) => `__smNodeAssertFreeze({ ${names.map(name => `${name}: ${map.get(name)}`).join(', ')} })`;
const factory = `(() => {\nconst __smNodeAssertFreeze = Object.freeze;\n${body}\nreturn () => __smNodeAssertFreeze({ root: ${record(rootNames, bindings)}, strict: ${record(strictNames, strictBindings)} });\n})()`;
if (factory.includes(')SM_NODE_PROFILE"')) throw new Error('Assert raw-string delimiter collision');
const digest = createHash('sha256');
for (const name of names) digest.update(name+'\0'+sources[name]+'\0');
const output = '// Generated by generate-assert-factories.mjs; do not edit.\n'+
  `// Canonical-source SHA-256: ${digest.digest('hex')}\n`+
  `static constexpr const char kAssertFactorySource[] = R"SM_NODE_PROFILE(${factory})SM_NODE_PROFILE";\n`;
const path = join(directory, 'assert-factories.generated.h');
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== output) throw new Error('Stale assert-factories.generated.h');
  console.log('PASS optional Assert factory/schema/export graph matches canonical sources');
} else await writeFile(path, output);
