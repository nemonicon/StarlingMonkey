// Independent optional StringDecoder packaging; no shared generator/build edits.
// Run: node builtins/node-compat/generate-string-decoder-factory.mjs [--check]
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {validateManifest} from './validate-manifest.mjs';
const directory=dirname(fileURLToPath(import.meta.url));
const names=['string-decoder.mjs','export-manifest.string-decoder.node-v22.14.0.json'];
const sources=Object.fromEntries(await Promise.all(names.map(async name=>[name,await readFile(join(directory,name),'utf8')])));
const manifest=JSON.parse(sources[names[1]]);
validateManifest(manifest,JSON.parse(await readFile(join(directory,'manifest.schema.json'),'utf8')));
if(manifest.profileVersion!=='sm-node-22.14.0-m0.4')throw Error('Unexpected StringDecoder profile version');
if(Object.keys(manifest.modules).join(',')!=='node:string_decoder')throw Error('Unexpected StringDecoder module inventory');
const module=manifest.modules['node:string_decoder'];
if(module.exports.join(',')!=='StringDecoder,default'||module.aliases.join(',')!=='string_decoder')throw Error('Unexpected StringDecoder exports/aliases');
let body=sources['string-decoder.mjs'];
const declaration='export function createStringDecoderModule(Buffer) {';
if(body.split(declaration).length!==2)throw Error('Missing unique one-argument StringDecoder factory');
body=body.replace(declaration,'function createStringDecoderModule(Buffer) {');
if(!body.includes('return { StringDecoder, default: { StringDecoder } };'))throw Error('Unexpected StringDecoder module-record shape');
if(/^\s*(?:import|export)\b/m.test(body))throw Error('Unsupported StringDecoder source syntax');
const factory=`(() => {\n${body}\nreturn createStringDecoderModule;\n})()`;
if(factory.includes(')SM_NODE_PROFILE"'))throw Error('StringDecoder raw-string delimiter collision');
const digest=createHash('sha256');
for(const name of names)digest.update(name+'\0'+sources[name]+'\0');
const output='// Generated by generate-string-decoder-factory.mjs; do not edit.\n'+
  `// Canonical-source SHA-256: ${digest.digest('hex')}\n`+
  `static constexpr const char kStringDecoderFactorySource[] = R"SM_NODE_PROFILE(${factory})SM_NODE_PROFILE";\n`;
const path=join(directory,'string-decoder-factories.generated.h');
if(process.argv.includes('--check')){
  if(await readFile(path,'utf8')!==output)throw Error('Stale string-decoder-factories.generated.h');
  console.log('PASS optional StringDecoder factory/schema/exports match canonical sources');
}else await writeFile(path,output);
