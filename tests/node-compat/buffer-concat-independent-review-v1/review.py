def script(name):
    text = re.sub(r"^import \{ (?:unavailable, unsupported|unsupported) \} from '\./unsupported\.mjs';\n", '', sources[name], flags=re.M)
    text = re.sub(r'^export (const|function) ', r'\1 ', text, flags=re.M)
    text = re.sub(r'^export default Object\.freeze\(', 'const defaultExport = Object.freeze(', text, flags=re.M)
    assert not re.search(r'^\s*(?:import|export)\b', text, re.M)
    return text


