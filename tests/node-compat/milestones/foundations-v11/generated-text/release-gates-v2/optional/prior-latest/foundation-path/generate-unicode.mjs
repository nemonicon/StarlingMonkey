// Maintainer-only extraction from the pinned Node/V8 Unicode category oracle.
// Normal builds consume the checked-in finite table without Intl or host calls.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
assert.equal(process.version, 'v22.14.0');
assert.equal(process.versions.unicode, '16.0');
const here = dirname(fileURLToPath(import.meta.url));
const repository = resolve(here, '../../..');
const names = ['L', 'Nl', 'Nd', 'Zs', 'Cc', 'Z', 'C', 'Ll', 'P', 'S', 'Lu', 'Pc'];
const categories = Object.create(null), details = [];
const escape = point => '\\u{' + point.toString(16) + '}';
for (const name of names) {
  const oracle = new RegExp('^\\p{' + name + '}$', 'u');
  const intervals = [];
  let start = -1;
  for (let point = 0; point <= 0x110000; point++) {
    const present = point < 0x110000 && oracle.test(String.fromCodePoint(point));
    if (present && start < 0) start = point;
    else if (!present && start >= 0) { intervals.push([start, point - 1]); start = -1; }
  }
  const source = intervals.map(([first, last]) => escape(first) + (first === last ? '' : '-' + escape(last))).join('');
  const candidate = new RegExp('^[' + source + ']$', 'u');
  // Include the complete code-point domain, including lone surrogate values.
  for (let point = 0; point < 0x110000; point++) {
    const value = String.fromCodePoint(point);
    assert.equal(candidate.test(value), oracle.test(value), name + ' at U+' + point.toString(16));
  }
  categories[name] = source;
  details.push({ name, intervals: intervals.length, sourceCodeUnits: source.length, codePointsCompared: 0x110000 });
}
const result = '// Generated by foundation-path/generate-unicode.mjs; do not edit.\n' +
  '// Exact Node v22.14.0 / Unicode16.0 category intervals, including surrogates.\n' +
  '// Only the finite POSIX-glob category allowlist is represented.\n' +
  'export const unicodeCategoryRanges = ' + JSON.stringify(categories, null, 2) + ';\n';
const destination = join(repository, 'builtins/node-compat/path-vendor/unicode-categories.mjs');
if (process.argv.includes('--check')) assert.equal(await readFile(destination, 'utf8'), result, 'Stale Unicode category table');
else await writeFile(destination, result);
const report = { schema: 1, node: process.version, unicode: process.versions.unicode,
  generation: 'Exhaustive category oracle extraction and independent generated-range RegExp comparison for every code point0..0x10ffff, including surrogate values.',
  categories: details, comparisons: names.length * 0x110000,
  generatedPath: 'builtins/node-compat/path-vendor/unicode-categories.mjs',
  generatedSha256: createHash('sha256').update(result).digest('hex'),
  generatorSha256: createHash('sha256').update(await readFile(fileURLToPath(import.meta.url))).digest('hex') };
await writeFile(join(here, 'unicode-results.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({ categories: names.length, comparisons: report.comparisons,
  generatedSha256: report.generatedSha256, checked: process.argv.includes('--check') }, null, 2));
