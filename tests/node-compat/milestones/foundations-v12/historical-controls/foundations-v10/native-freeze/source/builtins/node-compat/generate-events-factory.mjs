// Independent optional Events packaging. Normal CMake builds consume the header.
import {readFile, writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import vm from 'node:vm';
import * as pinnedEvents from 'node:events';
import {validateManifest} from './validate-manifest.mjs';

if (process.version !== 'v22.14.0') throw new Error('Events generation requires exact Node v22.14.0');
const directory = dirname(fileURLToPath(import.meta.url));
const names = ['events-add-abort-listener.mjs', 'events.mjs', 'export-manifest.events.node-v22.14.0.json'];
const sources = Object.fromEntries(await Promise.all(names.map(async name => [name, await readFile(join(directory, name), 'utf8')])));
const manifest = JSON.parse(sources[names[2]]);
validateManifest(manifest, JSON.parse(await readFile(join(directory, 'manifest.schema.json'), 'utf8')));
if (manifest.profileVersion !== 'sm-node-22.14.0-m0.10' || Object.keys(manifest.modules).join() !== 'node:events') throw new Error('Unexpected Events profile');
const modulePolicy = manifest.modules['node:events'];
if (modulePolicy.aliases.join() !== 'events' || [...modulePolicy.exports].sort().join() !== Object.keys(pinnedEvents).sort().join()) throw new Error('Not the exact pinned Node22 Events namespace');
if (!modulePolicy.supportedStatic.includes('addAbortListener') || modulePolicy.unsupportedStatic.includes('addAbortListener')) throw new Error('Unexpected addAbortListener policy');
let helper = sources[names[0]].replace(/^export function /gm, 'function ');
let facade = sources[names[1]];
const statement = "import {createAddAbortListener} from './events-add-abort-listener.mjs';\n";
if (facade.split(statement).length !== 2) throw new Error('Missing or duplicate private helper binding');
facade = facade.replace(statement, '').replace(/^export function /gm, 'function ');
if (/^\s*(?:import|export)\b/m.test(helper + facade)) throw new Error('Unsupported Events source syntax');
const factory = `(function(resistStopSymbol){\n'use strict';\n${helper}\n${facade}\nreturn createEventsFacade(resistStopSymbol);\n})`;
if (factory.includes(')SM_NODE_PROFILE"')) throw new Error('Events raw-string delimiter collision');

// Reflect only the finite graph. No listener, native key or native event target
// is simulated or invoked on the build host. The unique argument is not Node's
// private protected-option Symbol and must never be used as native proof.
const emitted = new vm.Script('"use strict";\n' + factory, {filename: '<generated-events-factory>'}).runInThisContext();
if (typeof emitted !== 'function' || emitted.length !== 1) throw new Error('Events factory needs one private Symbol argument');
const record = emitted(Symbol('build-only-events-key'));
if (Object.keys(record).sort().join() !== [...modulePolicy.exports].sort().join() || record.then !== undefined) throw new Error('Events finite namespace differs from manifest');
if (record.default !== record.EventEmitter || record.default.EventEmitter !== record.EventEmitter) throw new Error('Events default graph differs');
for (const name of modulePolicy.exports) {
  if (name === 'default' || name === 'defaultMaxListeners' || name === 'captureRejections') continue;
  if (record[name] !== record.default[name]) throw new Error('Events named/default identity differs: ' + name);
}
if (typeof record.errorMonitor !== 'symbol' || record.captureRejectionSymbol !== Symbol.for('nodejs.rejection') || record.defaultMaxListeners !== 10 || record.captureRejections !== false || record.usingDomains !== false) throw new Error('Events constant types differ');
for (const name of ['once', 'on', 'EventEmitterAsyncResource']) for (const construct of [false, true]) {
  let error;
  try { if (construct) new record[name](); else record[name](); } catch (caught) { error = caught; }
  if (error?.code !== 'ERR_SM_NODE_UNSUPPORTED' || error.module !== 'node:events' || error.profile !== manifest.profileVersion) throw new Error('Unbound Events unsupported helper: ' + name);
  for (const key of ['code', 'module', 'operation', 'profile']) if (!Object.hasOwn(error, key)) throw new Error('Events error lacks own field: ' + key);
}

const digest = createHash('sha256');
for (const name of names) digest.update(name + '\0' + sources[name] + '\0');
const output = '// Generated by generate-events-factory.mjs; do not edit.\n' +
  `// Canonical-source SHA-256: ${digest.digest('hex')}\n` +
  `static constexpr const char kEventsFactorySource[] = R"SM_NODE_PROFILE(${factory})SM_NODE_PROFILE";\n`;
const path = join(directory, 'events-factories.generated.h');
if (process.argv.includes('--check')) {
  if (await readFile(path, 'utf8') !== output) throw new Error('Stale Events factory header');
  console.log('PASS optional Events exact Node22 inventory, strict finite graph and helper bindings');
} else await writeFile(path, output);
