// Isolated optional stream factory; does not invoke the resulting factory.
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {dirname,join} from 'node:path';
import vm from 'node:vm';
const here=dirname(fileURLToPath(import.meta.url));
const source=await readFile(join(here,'stream-facade.mjs'),'utf8');
const manifest=await readFile(join(here,'../export-manifest.zlib-streaming.node-v22.14.0.json'),'utf8');
const parsed=JSON.parse(manifest);
if(process.version!=='v22.14.0'||parsed.profileVersion!=='sm-node-22.14.0-m0.21')throw Error('Pinned stream profile required');
const body=source.replace(/^export function /m,'function ');
if(/^\s*(?:import|export)\b/m.test(body))throw Error('Unexpected factory syntax');
const factory=`((dependencies)=>{\n${body}\nreturn createStreamingZlibModule(dependencies);\n})`;
new vm.Script(factory); // grammar only, no factory/kernel invocation
if(factory.includes(')SM_NODE_PROFILE"'))throw Error('Raw delimiter collision');
const hash=createHash('sha256').update('stream-facade.mjs\0'+source+'\0export-manifest.zlib-streaming.node-v22.14.0.json\0'+manifest+'\0').digest('hex');
const output=`// Generated by generate-stream-factory.mjs; do not edit.\n// Canonical-source SHA-256: ${hash}\nstatic constexpr const char kStreamingZlibFactorySource[] = R"SM_NODE_PROFILE(${factory})SM_NODE_PROFILE";\n`;
const file=join(here,'stream-factories.generated.h');
if(process.argv.includes('--check')){if(await readFile(file,'utf8')!==output)throw Error('Stale stream factory');}else await writeFile(file,output);
console.log('PASS streaming zlib factory grammar/source digest');
