// Template build tool. Usage:
// node generate-factories.mjs /absolute/rolldown/dist/index.mjs /absolute/output-dir
// Supply audited Rolldown 1.2.16 from the Jco lock, not a floating npx.
import { pathToFileURL, fileURLToPath } from 'node:url';
import { resolve, dirname, join } from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';

const [rolldownModule, outputDirectory] = process.argv.slice(2);
if (!rolldownModule || !outputDirectory) throw new Error('expected rolldown module and output directory');
const { rolldown } = await import(pathToFileURL(resolve(rolldownModule)).href);
const here = dirname(fileURLToPath(import.meta.url));
const sources = [
  ['kBufferFactorySource', 'export { createBufferModule as default } from "./buffer-facade.mjs";'],
  ['kChildProcessFactorySource', 'import * as child from "./child-process.mjs"; export default () => child;'],
];
const definitions = [];
for (const [name, contents] of sources) {
  // A single virtual entry leaves imported source modules at their real paths.
  const entry = join(here, `${name}.generated-entry.mjs`);
  const bundle = await rolldown({
    input: entry, platform: 'neutral', treeshake: false,
    plugins: [{ name: 'node-profile-entry',
      resolveId(id) { if (id === entry) return entry; },
      load(id) { if (id === entry) return contents; },
    }],
  });
  const result = await bundle.generate({ format: 'iife', name: '__nodeProfileFactory', exports: 'named' });
  await bundle.close();
  // Evaluate the IIFE exports container and yield its default factory function.
  const expression = result.output[0].code + '\n__nodeProfileFactory.default;\n';
  definitions.push(`static constexpr const char ${name}[] = ${JSON.stringify(expression)};`);
}
await mkdir(resolve(outputDirectory), { recursive: true });
await writeFile(join(resolve(outputDirectory), 'node-profile-factories.generated.h'),
  '// Generated by generate-factories.mjs; never edit.\n' + definitions.join('\n') + '\n');
